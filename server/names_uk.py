_APOS = str.maketrans({"’": "'", "ʼ": "'", "`": "'", "ё": "е"})


def norm(word: str) -> str:
    return word.lower().translate(_APOS).strip("'-")


def full_forms(word: str) -> set[str]:
    """The full names this word may stand for (itself included): «катя» → {катерина}, «саша» → both."""
    w = norm(word)
    found = {w}
    for full, forms in _FORMS.items():
        if w == full or w in forms:
            found.add(full)
    return found


def is_known_name(word: str) -> bool:
    w = norm(word)
    return any(w == full or w in forms for full, forms in _FORMS.items())
